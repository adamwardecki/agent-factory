// `upgrade <sha>`: re-renders the callers at a new pin, in a pull request. The templates come from the release
// itself, not from the local clone, so what the PR proposes is what that release expects. A release whose caller
// interface or state version is more than one step away is refused: a release reads its own state version and the
// one before it, so skipping one would strand the issues in flight.

import { defaultBranch, listComments, readRepoFile } from '../router/github.ts';
import { stateVersion } from '../router/markers.ts';
import { CALLERS, callerVars, render } from '../scripts/render-callers.ts';
import type { Host } from './host.ts';
import { changedFiles, commitExists, type FileChange, issuesInFlight, parsePin, proposeFiles, releaseVersions } from './repo.ts';

// The version of an issue's newest state comment; null when it has none.
function latestStateVersion(comments: readonly { body: string }[]): number | null {
  for (let i = comments.length - 1; i >= 0; i--) {
    const v = stateVersion(comments[i]?.body ?? '');
    if (v !== null) return v;
  }
  return null;
}

export async function upgrade(h: Host, sha: string): Promise<{ pr: number | null; message: string }> {
  if (!/^[0-9a-f]{40}$/.test(sha)) throw new Error('upgrade needs a full 40-character commit SHA of the factory repo');
  if (!(await commitExists(h.factory, sha))) throw new Error(`${sha} isn't a commit of ${h.factory.repo}`);
  const base = await defaultBranch(h.gh);
  const router = await readRepoFile(h.gh, `.github/workflows/${CALLERS[0]}`, base);
  const pin = router === null ? null : parsePin(router);
  if (!pin) throw new Error(`no pinned caller on ${base}; run init first`);
  if (pin.factoryRepo !== h.factory.repo) throw new Error(`the callers pin ${pin.factoryRepo}, not ${h.factory.repo}; pass --factory ${pin.factoryRepo}`);
  if (pin.sha === sha) return { pr: null, message: `the callers already pin ${sha}` };

  const from = await releaseVersions(h.factory, pin.sha);
  const to = await releaseVersions(h.factory, sha);
  for (const [what, a, b] of [['caller interface', from.interface, to.interface], ['state version', from.state, to.state]] as const) {
    if (b < a) throw new Error(`${sha} has ${what} ${b}, older than the pinned release's ${a}; a downgrade would leave state it can't read`);
    if (b > a + 1) throw new Error(`${sha} has ${what} ${b}, more than one step from ${a}; upgrade to a release with ${what} ${a + 1} first, and let the issues in flight move on`);
  }
  // The new release reads its own state version and the one before. An issue still holding an older state, from
  // before the pinned release, would be left alone for good: wait until the pinned release has rewritten it.
  if (to.state > from.state) {
    for (const issue of await issuesInFlight(h.gh)) {
      const v = latestStateVersion(await listComments(h.gh, issue));
      if (v !== null && v < from.state) throw new Error(`#${issue} still holds state version ${v}; ${sha} reads only ${to.state - 1} and ${to.state}. Let the pinned release move it on (any router run rewrites it), then upgrade`);
    }
  }

  const vars = callerVars(h.factory.repo, sha, pin.cron ?? '*/30 * * * *');
  const files: FileChange[] = [];
  for (const name of CALLERS) {
    const template = await readRepoFile(h.factory, `templates/${name}`, sha);
    if (template === null) throw new Error(`${h.factory.repo}@${sha} has no templates/${name}`);
    files.push({ path: `.github/workflows/${name}`, content: render(template, vars) });
  }
  const changed = await changedFiles(h.gh, base, files);
  if (changed.length === 0) return { pr: null, message: `the callers already match ${sha}` };
  const short = sha.slice(0, 7);
  const body = `Moves the agent factory's callers from \`${pin.sha}\` to \`${sha}\` (${h.factory.repo}). Generated by \`cli/factory.ts upgrade\`.\n\nRead the release's changelog before merging.`;
  const r = await proposeFiles(h.gh, `factory/upgrade-${short}`, changed, `Upgrade the agent factory to ${short}`, body);
  return { pr: r.pr, message: r.created ? `opened upgrade PR #${r.pr}` : `upgrade PR #${r.pr} is already open` };
}
